"""Symbol files: persist and reuse human-readable names for addresses.

Disassembly is only useful if you can keep what you learned. A symbol file
maps addresses to labels, so the second analysis session starts where the
first one ended instead of showing ``L C013`` again.

Two widespread dialects are read; we emit the FCEUX-style one.

===========  ===================  =====================================
Format       Line shape           Used by
===========  ===================  =====================================
``.sym``     ``C013:main``        FCEUX, and this project's output
``.mlb``     ``C013#main``        Mesen label files
===========  ===================  =====================================

Comments start with ``;`` or ``#`` at the beginning of a line; blank lines
are ignored.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

_SYM_RE = re.compile(r"^\s*([0-9A-Fa-f]{1,6})\s*:\s*([^\s;#]+)\s*(?:;.*)?$")
_MLB_RE = re.compile(r"^\s*([0-9A-Fa-f]{1,6})\s*#\s*([^\s;#]+)\s*$")
_LABEL_RE = re.compile(r"^[A-Za-z_.][A-Za-z0-9_.@$]*$")


@dataclass
class SymbolTable:
    """Address -> label, plus the reverse index used for rendering."""

    labels: dict[int, str] = field(default_factory=dict)
    source: str | None = None

    # -- construction ------------------------------------------------------
    @classmethod
    def parse(cls, text: str, source: str | None = None) -> SymbolTable:
        table = cls(source=source)
        for lineno, raw in enumerate(text.splitlines(), start=1):
            line = raw.strip()
            if not line or line.startswith((";", "#")):
                continue
            m = _SYM_RE.match(line) or _MLB_RE.match(line)
            if not m:
                raise ValueError(f"{source or '<string>'}:{lineno}: cannot parse {line!r}")
            addr = int(m.group(1), 16)
            name = m.group(2)
            if not _LABEL_RE.match(name):
                raise ValueError(f"{source or '<string>'}:{lineno}: invalid label {name!r}")
            table.labels[addr] = name
        return table

    @classmethod
    def load(cls, path: str | Path) -> SymbolTable:
        p = Path(path)
        return cls.parse(p.read_text(encoding="utf-8"), source=str(p))

    @classmethod
    def merge(cls, *tables: SymbolTable) -> SymbolTable:
        """Later tables win, so a project file can override a generated one."""
        out = cls()
        for t in tables:
            out.labels.update(t.labels)
        return out

    # -- access ------------------------------------------------------------
    def get(self, address: int) -> str | None:
        return self.labels.get(address & 0xFFFF)

    def add(self, address: int, label: str) -> None:
        if not _LABEL_RE.match(label):
            raise ValueError(f"invalid label {label!r}")
        self.labels[address & 0xFFFF] = label

    def __len__(self) -> int:
        return len(self.labels)

    def __contains__(self, address: object) -> bool:
        return address in self.labels

    # -- output ------------------------------------------------------------
    def render(self, header: str | None = None) -> str:
        lines = []
        if header:
            lines += [f"; {ln}" for ln in header.splitlines()]
        lines.append("; address:label  (FCEUX / SuperMido symbol format)")
        for addr in sorted(self.labels):
            lines.append(f"{addr:04X}:{self.labels[addr]}")
        return "\n".join(lines) + "\n"

    def save(self, path: str | Path) -> None:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(self.render(header=f"generated by supermido from {self.source or 'disassembly'}"),
                     encoding="utf-8")


def auto_name(address: int, kind: str = "L") -> str:
    """Fallback label for an address that has no symbol yet."""
    return f"{kind}{address:04X}"
